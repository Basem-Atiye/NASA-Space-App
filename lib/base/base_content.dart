bool _registered = false;

/// Makes the events available to the engine (safe to call many times).
void ensureBaseContent() {
  if (_registered) return;
  _registered = true;
  registerEvents(_events);
}

List<EventDef> get allBaseEvents => _events;

BaseMission baseMission(int n) => n <= 5 ? moonMissions[n - 1] : marsMissions[n - 6];

/// A short "real science" line for the event.
String scienceFor(String eventId) => eventById(eventId)?.science ?? '';
